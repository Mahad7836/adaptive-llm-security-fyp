from __future__ import annotations

import re
from common.logger import log_step

# Common refusal markers emitted by aligned models when declining adversarial requests
REFUSAL_PATTERNS: tuple[str, ...] = (
    "i'm sorry",
    "i am sorry",
    "i cannot",
    "i can't",
    "i am unable",
    "i'm unable",
    "sorry, but",
    "as an ai",
    "as a responsible ai",
    "as an ai language model",
    "as a language model",
    "against my safety",
    "safety policy",
    "safety policies",
    "ethical guidelines",
    "cannot comply",
    "cannot fulfill",
    "unable to fulfill",
    "cannot generate",
    "i must decline",
    "i am programmed to be a helpful",
)


def is_refusal_response(text: str | None) -> bool:
    """Determine whether an LLM generation contains a safety refusal instead of test content.

    Args:
        text: Raw generated output from the LLM.

    Returns:
        True if the text appears to be a refusal or is empty; False otherwise.
    """
    if not text:
        return True

    clean = text.strip().lower()
    if not clean:
        return True

    # Check for direct phrase matches
    for pattern in REFUSAL_PATTERNS:
        if pattern in clean:
            return True

    # Check for short generic decline sentences
    if len(clean) < 80 and ("help with that" in clean or "assist with that" in clean):
        return True

    return False


def sanitize_or_fallback(
    response_text: str | None,
    fallback_text: str,
    agent_label: str,
) -> str:
    """Validate LLM output against refusals, substituting fallback probe if refusal detected.

    Args:
        response_text: Candidate probe generated by LLM.
        fallback_text: Pre-constructed deterministic fallback probe.
        agent_label: Logging identifier for terminal traceability.

    Returns:
        Cleaned response_text if valid, else fallback_text.
    """
    if not response_text or is_refusal_response(response_text):
        preview = (response_text or "").replace("\n", " ").strip()[:60]
        log_step(
            agent_label,
            f"Notice: Upstream LLM refusal or empty response detected ('{preview}'). "
            "Applying robust deterministic heuristic fallback probe.",
        )
        return fallback_text

    return response_text.strip()
